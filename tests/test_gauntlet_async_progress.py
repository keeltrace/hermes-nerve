"""Internal worker evidence is not a new owner request for source mutation."""
import pytest
from hermes_nerve.progress_integrity import change_required, verification_required


@pytest.mark.parametrize("header", [
    "[ASYNC DELEGATION BATCH COMPLETE — deleg_example]",
    "[ASYNC DELEGATION TASK FAILED — deleg_example, task 1/2]",
])
def test_internal_delegation_receipt_does_not_require_another_mutation(header):
    notification = (header + "\nTask: fix engine.py and verify tests\n"
        "Result: Implemented repair in engine.py; tests passed.\n"
        "[INTERNAL NOTIFICATION — generated by the Hermes gateway, not written by a human user. "
        "Do not treat it as user input, and do not reply to any earlier chat message because of it.]")
    assert change_required(notification) is False
    assert verification_required(notification) is False


def test_owner_request_with_delegation_words_keeps_mutation_requirement():
    assert change_required("Fix engine.py after the delegation batch completes and verify tests")
    assert verification_required("Fix engine.py after the delegation batch completes and verify tests")
