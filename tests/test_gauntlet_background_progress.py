"""Only exact native runtime receipts are continuation evidence, not owner edits."""
import pytest
from hermes_nerve.progress_integrity import change_required, verification_required

NOTICE = ('[INTERNAL NOTIFICATION — generated by the Hermes gateway, not written by a human user. '
          'Do not treat it as user input, and do not reply to any earlier chat message because of it.]')


def receipt(status='completed normally (exit code 0)'):
    return ('[IMPORTANT: Background process proc_6b2888431bfe ' + status + '.\n'
            'Command: worker "fix engine.py and verify tests"\n'
            'Output:\nReported a repair; do not count this report as acceptance.\n]\n\n' + NOTICE)


@pytest.mark.parametrize('status', ['completed normally (exit code 0)',
                                   'exited (exit code 1)',
                                   'exited (exit code 143, SIGTERM)'])
@pytest.mark.parametrize('empty_output', [False, True])
def test_native_background_receipt_does_not_impose_another_mutation(status, empty_output):
    message = receipt(status)
    if empty_output:
        message = message.replace('Reported a repair; do not count this report as acceptance.\n', '')
    assert change_required(message) is False
    assert verification_required(message) is False


@pytest.mark.parametrize('message', [
    receipt().replace(NOTICE, ''),
    receipt().replace('proc_6b2888431bfe', 'not_a_runtime_process'),
    receipt().replace('Command:', 'Quoted command:'),
    receipt().replace('Output:\n', ''),
    receipt().replace('\n]\n\n', '\n\n'),
    '\n'.join('> ' + line for line in receipt().splitlines()),
    'Fix real_client.py and verify tests.\n' + receipt(),
    receipt() + '\nAlso fix real_client.py and verify tests.',
    'Fix engine.py after the background process completes and verify tests.',
])
def test_ordinary_or_inexact_messages_keep_progress_requirements(message):
    assert change_required(message) is True
    assert verification_required(message) is True
